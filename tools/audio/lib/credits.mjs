// Regenerates the audio section of docs/CREDITS.md from the inventory (every downloaded CC0 source, with URL,
// author and licence) and tools/audio/provenance/*.json (which shipped category used which source).
// Only the text between the audio markers is touched; other generated sections (map, zombies...) are preserved.
import fs from 'node:fs';
import path from 'node:path';
import { CREDITS, INVENTORY, PROVENANCE } from './paths.mjs';

const BEGIN = '<!-- audio-sources:begin (generated by tools/audio/fetch.mjs + build.mjs - do not edit by hand) -->';
const END = '<!-- audio-sources:end -->';
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function loadProvenance() {
  const usedBy = new Map(); // source id -> Set("category:sound" | "category")
  const cats = [];
  if (!fs.existsSync(PROVENANCE)) return { usedBy, cats };
  for (const f of fs.readdirSync(PROVENANCE).filter((x) => x.endsWith('.json')).sort()) {
    const p = JSON.parse(fs.readFileSync(path.join(PROVENANCE, f), 'utf8'));
    cats.push(p);
    const add = (id, label) => { if (!usedBy.has(id)) usedBy.set(id, new Set()); usedBy.get(id).add(label); };
    for (const [snd, ids] of Object.entries(p.sounds || {})) for (const id of ids) add(id, `${p.category}/${snd}`);
    for (const id of p.loaded || []) {
      const already = [...(usedBy.get(id) || [])].some((l) => l.startsWith(p.category + '/'));
      if (!already) add(id, p.category);
    }
  }
  return { usedBy, cats };
}

export function renderCredits(inv) {
  const { usedBy, cats } = loadProvenance();
  const lines = [BEGIN, '### 音效素材 Audio sources (CC0)', ''];
  lines.push('Shipped sounds in `game/assets/audio/` are produced by `tools/audio/producers/*.mjs` from the CC0 recordings below',
    '(downloaded by `tools/audio/fetch.mjs` into the gitignored `tools/audio/src/`, licence re-checked on each source page) and from',
    'sounds synthesized from scratch. Every source here is CC0 1.0 (public domain); attribution is not required, listed for provenance.',
    `Inventory: ${inv.files.length} files from ${Object.keys(inv.packs).length} packs, generated ${inv.generated || '-'}.`, '');
  const usedLabel = (ids) => {
    const s = new Set();
    for (const id of ids) for (const l of usedBy.get(id) || []) s.add(l.split('/')[0]);
    return [...s].sort().join(', ') || '-';
  };
  // packs
  lines.push('| Pack | Author | Source page | License (verified) | Files | Used by categories |', '|---|---|---|---|---|---|');
  const packs = Object.entries(inv.packs).sort(([a], [b]) => a.localeCompare(b));
  for (const [id, p] of packs) {
    if (id === 'fs') continue;
    const files = inv.files.filter((f) => f.pack === id);
    lines.push(`| ${esc(p.title)} (\`${id}\`)${p.note ? ` — ${esc(p.note)}` : ''} | ${esc(p.author)} | [${esc(p.page.replace(/^https?:\/\//, ''))}](${p.page}) | ${esc(p.licence)} (${esc(p.verified || '-')}) | ${files.length} | ${usedLabel(files.map((f) => f.id))} |`);
  }
  // freesound files
  const fsFiles = inv.files.filter((f) => f.pack === 'fs').sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
  if (fsFiles.length) {
    lines.push('', '**Freesound** (CC0, high-quality Ogg previews from `cdn.freesound.org`; licence read from each sound page)', '',
      '| ID | Title | Author | Page | License | Used by |', '|---|---|---|---|---|---|');
    for (const f of fsFiles) lines.push(`| ${f.id.replace('fs:', '')} | ${esc(f.title)} | ${esc(f.author)} | [link](${f.url}) | ${esc(f.licence)} | ${[...(usedBy.get(f.id) || [])].sort().join(', ') || '-'} |`);
  }
  // pack files actually used
  const usedPack = inv.files.filter((f) => f.pack !== 'fs' && usedBy.has(f.id)).sort((a, b) => a.id.localeCompare(b.id));
  if (usedPack.length) {
    lines.push('', '**Pack files used in shipped sounds**', '', '| File | Pack page | Author | License | Used by |', '|---|---|---|---|---|');
    for (const f of usedPack) lines.push(`| \`${esc(f.id)}\` | [${esc(inv.packs[f.pack]?.title || f.pack)}](${f.url}) | ${esc(f.author)} | ${esc(f.licence)} | ${[...usedBy.get(f.id)].sort().join(', ')} |`);
  }
  const original = cats.filter((c) => c.original).map((c) => c.category);
  if (original.length) lines.push('', `Fully synthesized (no third-party audio): ${original.map((c) => `\`${c}\``).join(', ')}.`);
  lines.push(END);
  return lines.join('\n');
}

export function updateCredits() {
  if (!fs.existsSync(INVENTORY)) return false;
  const inv = JSON.parse(fs.readFileSync(INVENTORY, 'utf8'));
  const block = renderCredits(inv);
  // re-read right before writing: other pipelines regenerate their own sections of the same file
  let text = fs.existsSync(CREDITS) ? fs.readFileSync(CREDITS, 'utf8') : '# 素材來源 CREDITS\n';
  const a = text.indexOf('<!-- audio-sources:begin'), b = text.indexOf(END);
  if (a >= 0 && b > a) text = text.slice(0, a) + block + text.slice(b + END.length);
  else text = text.replace(/\s*$/, '\n\n') + block + '\n';
  fs.writeFileSync(CREDITS, text);
  return true;
}
