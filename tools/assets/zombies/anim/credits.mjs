// Writes the zombie-animation section of docs/CREDITS.md (between its own markers, leaving the rest
// of the file untouched). Called by build.mjs with the clip list so the table matches the GLB.
import fs from 'node:fs';
import path from 'node:path';
import { REPO } from './skeleton.mjs';

const BEGIN = '<!-- zombie-anims:begin (generated by tools/assets/zombies/anim/build.mjs - do not edit by hand) -->';
const END = '<!-- zombie-anims:end -->';

export function writeCredits(clips) {
  const by = (re) => clips.filter((c) => re.test(c.meta.source || '')).map((c) => `\`${c.name}\``).join(', ') || '-';
  const md = `${BEGIN}
### 殭屍動畫素材 Zombie animation sources

\`game/assets/zombies/anims.glb\` is built by \`tools/assets/zombies/anim/\` (our own BVH / glTF readers and
retargeter; no MPFB2 / MakeHuman code). Sources are downloaded by \`tools/assets/zombies/anim/fetch.mjs\`.

| Source | Author / site | License | Used for |
|---|---|---|---|
| [Universal Animation Library (Standard)](https://opengameart.org/node/174563) - \`universal_animation_librarystandard.zip\` | Quaternius | CC0 1.0 | ${by(/UAL1/)} |
| [Universal Animation Library 2 (Standard)](https://opengameart.org/content/universal-animation-library-2) - \`universal_animation_library_2standard.zip\` | Quaternius | CC0 1.0 | ${by(/UAL2/)} |
| [CMU Graphics Lab Motion Capture Database](http://mocap.cs.cmu.edu) - BVH conversion by Bruce Hahne (cgspeed), mirror [una-dinosauria/cmu-mocap](https://github.com/una-dinosauria/cmu-mocap) | Carnegie Mellon University | CMU mocap terms (free to use, modify and redistribute, also commercially; the motion data itself may not be resold) | ${by(/CMU/)} |
| [MPFB2](https://github.com/makehumancommunity/mpfb2) \`rig.game_engine.json\`, \`weights.game_engine.json\`, \`base.obj\` (assets only) | MakeHuman community | CC0 1.0 | skeleton rest pose, preview mannequin (dev only) |

CMU trials: 104_41 ZombieWalk, 120_22 Zombie, 91_24 HurtLegWalk, 90_18 RugPullFall, 14_33 climb ladder.
Keyframed clips (${by(/^procedural$/)}) and all retargeting / zombie post-processing are original work (MIT).

> The data used in this project was obtained from mocap.cs.cmu.edu. The database was created with funding from NSF EIA-0196217.
${END}`;
  const file = path.join(REPO, 'docs', 'CREDITS.md');
  let s = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '# 素材來源 CREDITS\n\n本專案程式碼為 MIT；以下列出所有第三方素材與授權。\n';
  const a = s.indexOf('<!-- zombie-anims:begin'), b = s.indexOf(END);
  if (a >= 0 && b > a) s = s.slice(0, a) + md + s.slice(b + END.length);
  else s = s.replace(/\s*$/, '\n\n') + md + '\n';
  fs.writeFileSync(file, s);
}
