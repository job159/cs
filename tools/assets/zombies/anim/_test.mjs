import path from 'node:path';
import { Skeleton, REPO } from './skeleton.mjs';
import { ual1, ual2, cmu, MAP_UE, MAP_CMU } from './sources.mjs';
import { retarget } from './retarget.mjs';
import { makeClip, crop, removeRootMotion, fixSigns } from './clip.mjs';
import { GLBBuilder, addSkeleton, addClips } from './glb-write.mjs';
const skel = new Skeleton();
const clips = [];
let t = Date.now();
const a = makeClip('ual_zwalk', retarget(ual2('Zombie_Walk_Fwd_Loop'), MAP_UE, skel, { finger3: true }));
clips.push(a);
clips.push(makeClip('ual_zidle', retarget(ual2('Zombie_Idle_Loop'), MAP_UE, skel, { finger3: true })));
clips.push(makeClip('ual_tpose', retarget(ual2('A_TPose'), MAP_UE, skel, { finger3: true })));
console.log('ual', Date.now() - t); t = Date.now();
const b = makeClip('cmu_104_41', retarget(cmu('104_41', { from: 4, to: 8 }), MAP_CMU, skel, { heading: 'travel' }));
clips.push(b);
clips.push(makeClip('cmu_120_22', retarget(cmu('120_22', { from: 5.5, to: 9 }), MAP_CMU, skel, { heading: 'travel' })));
console.log('cmu', Date.now() - t);
for (const c of clips) { removeRootMotion(c); fixSigns(c); c.loop = true; }
const g = new GLBBuilder();
const ids = addSkeleton(g, skel);
const keys = addClips(g, skel, ids, clips);
g.json.scenes[0].extras = { clips: Object.fromEntries(clips.map((c) => [c.name, { loop: c.loop, speed: c.meta.speed || 0 }])) };
console.log('bytes', g.write(path.join(REPO, 'game', 'dev', 'test_anims.glb')), 'keys', keys, clips.map(c => c.name + ':' + c.meta.speed?.toFixed(2) + ' k=' + c.meta.scale?.toFixed(3)).join(' '));
