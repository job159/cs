// Provenance: every asset folder a build pulls (fetch.mjs `usage`) is merged into credits.json (committed)
// and rendered into the zombie section of docs/CREDITS.md between the zombie-assets markers.
import fs from 'node:fs';
import path from 'node:path';
import { usage, zipEntry, PACKS, ZROOT } from './fetch.mjs';

const MANIFEST = path.join(ZROOT, 'credits.json');
const CREDITS = path.resolve(ZROOT, '..', '..', '..', 'docs', 'CREDITS.md');
const MH = 'MakeHuman team (Data Collection AB, Joel Palmius, Jonas Hauquier)';

async function packMeta(pack) {
  try { return JSON.parse(fs.readFileSync(await zipEntry(pack, `packs/${pack === 'system' ? 'makehuman_system_assets' : pack}.json`), 'utf8')); } catch { return {}; }
}

export async function updateCredits() {
  const old = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) : {};
  const metas = {};
  for (const key of usage) {
    if (old[key]) continue;
    const [pack, folder] = key.split(/:(.*)/s);
    if (pack === 'mpfb2') {
      old[key] = { asset: folder, source: `https://github.com/makehumancommunity/mpfb2/tree/master/src/mpfb/data/${folder}`, author: MH, license: 'CC0-1.0' };
      continue;
    }
    metas[pack] ||= await packMeta(pack);
    const name = folder.split('/')[1];
    const m = metas[pack][name] || {};
    old[key] = {
      asset: folder,
      source: m.source && m.source !== 'http://www.makehumancommunity.org' ? m.source : PACKS[pack],
      download: PACKS[pack],
      author: m.author && m.author !== 'makehuman_system' ? m.author : MH,
      license: (m.license || 'CC0') === 'CC0' ? 'CC0-1.0' : m.license,
    };
  }
  const keys = Object.keys(old).sort();
  fs.writeFileSync(MANIFEST, JSON.stringify(Object.fromEntries(keys.map((k) => [k, old[k]])), null, 1) + '\n');
  const rows = keys.map((k) => {
    const e = old[k];
    return `| \`${e.asset}\` | ${k.startsWith('mpfb2') ? 'MPFB2 data' : k.split(':')[0] + ' pack'} | [link](${e.source}) | ${e.author} | ${e.license} |`;
  });
  const section = `<!-- zombie-assets:begin (generated by tools/assets/zombies/build.mjs - do not edit by hand) -->
### 殭屍角色素材 Zombie character assets (CC0)

Characters in \`game/assets/zombies/<type>.glb\` are converted from MakeHuman / MPFB2 **assets** (CC0 1.0; the
MakeHuman AGPL / MPFB2 GPL *code* is not used - the loaders in \`tools/assets/zombies/lib\` are our own). Asset
packs are read with HTTP Range from https://static.makehumancommunity.org/assets/assetpacks/index.html
(\`makehuman_system_assets_cc0.zip\`, \`skins03_cc0.zip\`); base mesh, targets, rig and weights from
https://github.com/makehumancommunity/mpfb2 (\`src/mpfb/data\`, assets licensed CC0 per its LICENSE.md).
Procedural zombie overlays (pallor, veins, wounds, blood, tears) are generated by our pipeline (MIT).

| Asset | From | Source | Author | License |
|---|---|---|---|---|
${rows.join('\n')}
<!-- zombie-assets:end -->`;
  let md = fs.existsSync(CREDITS) ? fs.readFileSync(CREDITS, 'utf8') : '# 素材來源 CREDITS\n';
  const re = /<!-- zombie-assets:begin[\s\S]*?<!-- zombie-assets:end -->/;
  md = re.test(md) ? md.replace(re, section) : md.trimEnd() + '\n\n' + section + '\n';
  fs.writeFileSync(CREDITS, md);
  return keys.length;
}
